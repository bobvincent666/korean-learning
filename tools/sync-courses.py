"""Copy the Korea notes and compile their Markdown into static course data."""
import hashlib
import html
import json
from pathlib import Path
import re
import shutil
import sys
from urllib.parse import quote

import markdown

ROOT = Path(__file__).resolve().parent.parent
COURSES = ROOT / 'courses'
SUMMARIES = {
    1: '认识韩语元音、辅音与四组拼读表。',
    2: '礼貌表达、去某地、日常对话与五组练习。',
    3: '主语助词、存在位置、位置词与六组练习。',
    4: '动作发生的场所、过去时与四组练习。',
    5: '天气、四季、안 否定、그리고 连接与巩固练习。',
}


def flatten_toc(items):
    for item in items:
        if item['level'] <= 2:
            yield {'id': item['id'], 'title': html.unescape(re.sub(r'<[^>]+>', '', item['name']))}
        yield from flatten_toc(item.get('children', []))


def compile_course(text, number, title, source_name):
    references = re.findall(r'!\[\[([^\]|]+)(?:\|[^\]]*)?\]\]', text)
    for reference in references:
        filename = Path(reference).name
        if filename != reference or not (COURSES / 'image' / filename).is_file():
            raise ValueError(f'Missing or invalid course image: {reference}')
        text = text.replace(f'![[{reference}]]', f'![韩语元音与辅音分组拼读表](./courses/image/{quote(filename)})')

    # The source uses bold section labels in Lesson 05 instead of Markdown headings.
    text = re.sub(r'^\*\*(\d+\. [^\n]+|参考答案)\*\*[ \t]*$', r'## \1', text, flags=re.M)
    text = re.sub(r'_{3,}', lambda match: '\\_' * len(match.group()), text)
    parts = re.split(r'^#{1,6}\s+参考答案\s*$', text, maxsplit=1, flags=re.M)
    parser = markdown.Markdown(extensions=['tables', 'fenced_code', 'toc', 'sane_lists'])
    body = parser.convert(parts[0])
    outline = list(flatten_toc(parser.toc_tokens))
    # Keep the single page title at h1; source top-level headings become h2.
    body = re.sub(r'<(/?)h1\b', r'<\1h2', body)
    body = re.sub(r'<table>(.*?)</table>', r'<div class="course-table-scroll"><table>\1</table></div>', body, flags=re.S)
    if len(parts) == 2:
        answers = markdown.markdown(parts[1], extensions=['tables', 'sane_lists'])
        body += f'<details class="answer-box" id="course-answers"><summary>查看参考答案</summary>{answers}</details>'
        outline.append({'id': 'course-answers', 'title': '参考答案'})
    if number == 1:
        body += '<p class="course-practice-link"><a href="#hangul" data-route>打开互动拼读表，点击小喇叭练习 →</a></p>'
    return {
        'id': f'lesson-{number}', 'number': number, 'title': title,
        'summary': SUMMARIES.get(number, title),
        'source': f'courses/{source_name}', 'html': body, 'outline': outline,
    }


def sync(source=None):
    source = Path(source).resolve() if source else COURSES
    notes = sorted(source.glob('[0-9][0-9]*.md'))
    if not notes:
        raise ValueError(f'No numbered course notes found in {source}')
    numbers = [int(note.name[:2]) for note in notes]
    if numbers != list(range(1, len(notes) + 1)):
        raise ValueError('Course numbers must be unique and consecutive, starting at 01')

    texts = [(note, note.read_text(encoding='utf-8-sig')) for note in notes]
    images = set()
    for _, text in texts:
        for reference in re.findall(r'!\[\[([^\]|]+)(?:\|[^\]]*)?\]\]', text):
            image = source / 'image' / reference
            if Path(reference).name != reference or not image.is_file():
                raise ValueError(f'Missing or invalid course image: {reference}')
            images.add(image)

    COURSES.mkdir(exist_ok=True)
    (COURSES / 'image').mkdir(exist_ok=True)
    if source != COURSES:
        for note, _ in texts:
            shutil.copy2(note, COURSES / note.name)
        for image in images:
            shutil.copy2(image, COURSES / 'image' / image.name)

    lessons = []
    for note, text in texts:
        number = int(note.name[:2])
        title = note.stem[2:].strip()
        lesson = compile_course(text, number, title, note.name)
        lesson['sourceHash'] = hashlib.sha256((COURSES / note.name).read_bytes()).hexdigest()
        lessons.append(lesson)
    output = '// Generated by tools/sync-courses.py from courses/*.md.\nexport const courses = '
    output += json.dumps(lessons, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'course-data.js').write_text(output, encoding='utf-8', newline='\n')
    print(f'Synced {len(lessons)} complete courses and {len(images)} image(s).')
    for lesson in lessons:
        print(f"{lesson['number']:02d} {lesson['title']}")


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    try:
        sync(sys.argv[1] if len(sys.argv) > 1 else None)
    except (OSError, ValueError) as error:
        raise SystemExit(str(error))
